export const getTurbineById = (id) => TURBINE_FLEET.find(t => t.id === id);

export const getStatusLabel = (status) => ({
  running: 'Running',
  alert: 'Alert',
  maintenance: 'Maintenance',
  offline: 'Offline',
}[status] || 'Unknown');

export const getStatusColor = (status) => ({
  running: 'var(--green)',
  alert: 'var(--red)',
  maintenance: 'var(--orange)',
  offline: 'var(--text-secondary)',
}[status] || 'var(--text-secondary)');

export const getHealthColor = (score) => {
  if (score >= 85) return 'var(--green)';
  if (score >= 70) return 'var(--yellow)';
  if (score >= 55) return 'var(--orange)';
  return 'var(--red)';
};
